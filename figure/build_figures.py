PREAMBLE = r"""%(fonts)s
\usepackage[table]{xcolor}
\usepackage{booktabs,longtable,array,graphicx}
\usepackage{pgfplots}
\pgfplotsset{compat=1.18}
\usepackage[hidelinks]{hyperref}
\input{../rsi-macros.tex}
"""

# one table or figure per PDF, cropped to its content, for \includegraphics
STANDALONE = r"""\documentclass[border=4pt]{standalone}
%(preamble)s\begin{document}
%(body)s\end{document}
"""

# the paper list spans pages, so it gets an ordinary page layout
LISTDOC = r"""\documentclass[11pt]{article}
\usepackage[margin=2cm]{geometry}
%(preamble)s\pagestyle{empty}
\begin{document}
\input{../tab-papers.tex}
\end{document}
"""

FLOAT_LINE = re.compile(r"^\\(begin|end)\{(table|figure)\*?\}|^\\(caption|label)\{|^\\centering$")


def strip_float(tex):
    """The content of a generated table/figure without its float, caption and label."""
    return "".join(l for l in tex.splitlines(True) if not FLOAT_LINE.match(l) and not l.startswith("%"))


def compile_pdfs(out, sources, fonts):
    """Compile every table and figure to out/pdf/<name>.pdf; aux files stay in out/build/."""
    build, pdf = out / "build", out / "pdf"
    build.mkdir(exist_ok=True)
    pdf.mkdir(exist_ok=True)
    pre = PREAMBLE % {"fonts": fonts}
    docs = {name[:-4]: (LISTDOC % {"preamble": pre} if name == "tab-papers.tex"
                        else STANDALONE % {"preamble": pre, "body": strip_float(tex)})
            for name, tex in sources.items()}
    for stem, doc in docs.items():
        # prefixed so preview.tex's \input{tab-x.tex} never finds these wrappers in the outdir
        (build / f"pdf-{stem}.tex").write_text(doc, encoding="utf-8")
    jobs = [(stem, build, f"pdf-{stem}") for stem in docs] + [("preview", out, "preview")]
    failed = []
    for stem, cwd, job in jobs:
        res = subprocess.run(["latexmk", "-xelatex", "-interaction=nonstopmode", "-halt-on-error",
                              "-quiet", f"-outdir={build}", f"{job}.tex"], cwd=cwd,
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if res.returncode:
            failed.append(f"{stem} (log: {build / (job + '.log')})")
        else:
            shutil.copy(build / f"{job}.pdf", pdf / f"{stem}.pdf")
    if failed:
        sys.exit("LaTeX failed: " + "; ".join(failed))
    print(f"compiled {len(jobs)} PDFs to {pdf}")


OUTPUTS = {
    "tab-levels.tex": tab_levels,
    "tab-domain-depth.tex": tab_domain_depth,
    "tab-feedback-depth.tex": tab_feedback_depth,
    "tab-domain-feedback.tex": tab_domain_feedback,
    "fig-timeline.tex": fig_timeline,
    "fig-loop.tex": fig_loop,
    "tab-papers.tex": tab_papers,
}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", default=str(pl.DATA), help="TSV file (default: data/papers.tsv)")
    ap.add_argument("--out", default=str(HERE / "generated"), help="output directory")
    ap.add_argument("--status", choices=["all", "confirmed"], default="all",
                    help="'confirmed' keeps only confirmed rows")
    ap.add_argument("--pdf", action="store_true", help="also compile every table and figure to pdf/ with latexmk -xelatex")
    a = ap.parse_args()
    src = Path(a.data).resolve()
    rows = load(src, a.status)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    try:
        shown = src.relative_to(pl.ROOT)
    except ValueError:
        shown = src.name
    head = HEADER.format(src=shown, n=len(rows), conf=sum(r["status"] == pl.STATUS_CONFIRMED for r in rows))
    (out / "rsi-macros.tex").write_text(head + MACROS, encoding="utf-8")
    (out / "rsi-stats.tex").write_text(head + stats(rows), encoding="utf-8")
    sources = {name: fn(rows) for name, fn in OUTPUTS.items()}
    for name, tex in sources.items():
        (out / name).write_text(head + tex, encoding="utf-8")
    body = "\n".join(rf"\input{{{n}}}" for n in OUTPUTS if n != "tab-papers.tex")
    fonts = r"\usepackage{fontspec}"
    (out / "preview.tex").write_text(head + PREVIEW % {"fonts": fonts, "body": body}, encoding="utf-8")
    print(f"wrote {len(OUTPUTS) + 3} files to {out} ({len(rows)} papers from {shown})")
    if a.pdf:
        compile_pdfs(out, sources, fonts)


if __name__ == "__main__":
    main()
