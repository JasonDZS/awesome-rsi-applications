"""Generate LaTeX tables and figures for the survey from data/papers.tsv.

  python3 figure/build_figures.py                       # read data/papers.tsv
  python3 figure/build_figures.py --pdf                 # also compile pdf/<name>.pdf for each output
  python3 figure/build_figures.py --data data/local/unconfirmed-papers.tsv --pdf
                                                        # preview the layout with draft data

Output goes to figure/generated/ (or --out). Every file is generated: edit this script or the
data, not the .tex files. In the paper, \\input{rsi-macros.tex} once in the preamble, then
\\input{} any table or figure. See figure/README.md for the packages each file needs.
"""
