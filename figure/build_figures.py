# ---------------------------------------------------------------- data

def load(path, status):
    cols, rows = pl.load_tsv(path)
    if cols != pl.COLUMNS:
        sys.exit(f"{path}: the header does not match the columns in scripts/paperlib.py")
    out = []
    for r in rows:
        if not r.get("id"):
            continue
        # files still in the old Chinese vocabulary (e.g. local drafts) are converted on the fly
        r = pl.normalise({k: legacy_to_english(k, v or "") for k, v in r.items()})
        if status == "confirmed" and r["status"] != pl.STATUS_CONFIRMED:
            continue
        r["tag_list"] = [t for t in r["tags"].split(";") if t]
        m = re.match(r"R[0-4]", r["R"])
        r["level"] = m.group(0) if m else TBD
        r["fb_list"] = pl.split_multi(r["feedback"]) or [TBD]
        r["year"] = int(r["date"][:4]) if re.match(r"\d{4}", r["date"]) else None
        out.append(r)
    return out


# ---------------------------------------------------------------- LaTeX helpers

_ESC = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
        "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
        "²": r"\textsuperscript{2}", "π": r"$\pi$", "“": "``", "”": "''"}


def esc(s):
    return "".join(_ESC.get(ch, ch) for ch in s)


def heat_cell(v, vmax):
    if v == 0:
        return r"\rsizero"
    return rf"\rsiheat{{{round(10 + 60 * v / vmax) if vmax else 0}}}{{{v}}}"


def heat_table(row_labels, col_labels, grid, caption, label, corner, total_row=None, wide=False):
    """grid: list of rows of ints. Shaded by the largest cell."""
    vmax = max((v for row in grid for v in row), default=0)
    env = "table*" if wide else "table"
    lines = [rf"\begin{{{env}}}[t]", r"\centering", r"\small",
             rf"\begin{{tabular}}{{l{'c' * len(col_labels)}r}}", r"\toprule",
             f"{corner} & " + " & ".join(col_labels) + rf" & {TX['total']} \\", r"\midrule"]
    for name, row in zip(row_labels, grid):
        lines.append(f"{name} & " + " & ".join(heat_cell(v, vmax) for v in row) + f" & {sum(row)} \\\\")
    if total_row is not None:
        lines += [r"\midrule", f"{TX['unique']} & " + " & ".join(map(str, total_row))
                  + f" & {sum(total_row)} \\\\"]
    lines += [r"\bottomrule", r"\end{tabular}", rf"\caption{{{caption}}}", rf"\label{{{label}}}",
              rf"\end{{{env}}}"]
    return "\n".join(lines) + "\n"


def level_cols(rows):
    """R0..R4, plus an Unclear column only when some paper needs it."""
    return LEVELS + ([TBD] if any(r["level"] == TBD for r in rows) else [])


# ---------------------------------------------------------------- tables

def tab_levels(rows):
    c = Counter(r["level"] for r in rows)
    h = TX["level_head"]
    lines = [r"\begin{table}[t]", r"\centering", r"\small", r"\begin{tabular}{clr}", r"\toprule",
             " & ".join(h) + r" \\", r"\midrule"]
    for lv in LEVELS:
        ink = r"\color{white}" if lv in ("R3", "R4") else ""
        lines.append(rf"{{\setlength{{\fboxsep}}{{1.5pt}}\colorbox{{rsi{lv}}}{{{ink}\,{lv}\,}}}} & "
                     rf"{TX['levels'][lv]} & {c.get(lv, 0)} \\")
    if c.get(TBD):
        lines.append(rf"-- & {TX['tbd']} & {c[TBD]} \\")
    lines += [r"\bottomrule", r"\end{tabular}", rf"\caption{{{TX['cap_levels']}}}",
              r"\label{tab:rsi-levels}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def tab_domain_depth(rows):
    cols = level_cols(rows)
    grid = [[sum(1 for r in rows if d in r["tag_list"] and r["level"] == lv) for lv in cols]
            for d in pl.DOMAINS]
    names = [f"{d}. {TX['domains'][d]}" for d in pl.DOMAINS]
    total = [sum(1 for r in rows if r["level"] == lv) for lv in cols]
    heads = [TX["tbd"] if lv == TBD else lv for lv in cols]
    return heat_table(names, heads, grid, TX["cap_domain_depth"], "tab:rsi-domain-depth",
                      TX["domain"], total_row=total)


def tab_feedback_depth(rows):
    cols = level_cols(rows)
    fbs = FEEDBACK + ([TBD] if any(TBD in r["fb_list"] for r in rows) else [])
    grid = [[sum(1 for r in rows if f in r["fb_list"] and r["level"] == lv) for lv in cols] for f in fbs]
    heads = [TX["tbd"] if lv == TBD else lv for lv in cols]
    return heat_table([TX["feedback"][f] for f in fbs], heads, grid, TX["cap_feedback_depth"],
                      "tab:rsi-feedback-depth", TX["feedback_head"])


def tab_domain_feedback(rows):
    fbs = FEEDBACK + ([TBD] if any(TBD in r["fb_list"] for r in rows) else [])
    grid = [[sum(1 for r in rows if d in r["tag_list"] and f in r["fb_list"]) for f in fbs]
            for d in pl.DOMAINS]
    heads = [rf"\rotatebox{{90}}{{{TX['feedback'][f]}}}" for f in fbs]
    names = [f"{d}. {TX['domains'][d]}" for d in pl.DOMAINS]
    return heat_table(names, heads, grid, TX["cap_domain_feedback"], "tab:rsi-domain-feedback",
                      TX["domain"])


def tab_papers(rows):
    """Full list as a longtable (one-column layout; put it in an appendix)."""
    h = TX["cols"]
    head = " & ".join(rf"\textbf{{{x}}}" for x in h) + r" \\"
    spec = r"@{}l>{\raggedright\arraybackslash}p{0.29\linewidth}lc" \
           r"c>{\raggedright\arraybackslash}p{0.17\linewidth}" \
           r">{\raggedright\arraybackslash}p{0.12\linewidth}>{\raggedright\arraybackslash}p{0.10\linewidth}@{}"
    lines = [r"\begingroup\footnotesize\setlength{\tabcolsep}{3pt}", rf"\begin{{longtable}}{{{spec}}}",
             rf"\caption{{{TX['cap_papers']}}}\label{{tab:rsi-papers}}\\",
             r"\toprule", head, r"\midrule", r"\endfirsthead",
             rf"\multicolumn{{8}}{{@{{}}l}}{{\emph{{({TX['cont']})}}}}\\", r"\toprule", head, r"\midrule",
             r"\endhead", r"\midrule", rf"\multicolumn{{8}}{{r@{{}}}}{{\emph{{({TX['next']})}}}}\\",
             r"\endfoot", r"\bottomrule", r"\endlastfoot"]
    for r in sorted(rows, key=lambda r: (r["date"], r["id"])):
        title = esc(r["title"])
        paper = rf"\rsipaper{{{title}}}{{{esc(r['url'])}}}" if r["url"] else title
        fb = "; ".join(TX["feedback"].get(f, esc(f)) for f in r["fb_list"])
        lines.append(" & ".join([
            r["id"], paper, r["date"], ",".join(r["tag_list"]),
            r["level"] if r["level"] != TBD else "?", fb,
            TX["loop"].get(r["loop"], esc(r["loop"])) if r["loop"] else "--",
            TX["evidence"].get(r["evidence"], esc(r["evidence"])) if r["evidence"] else "--",
        ]) + r" \\")
    lines += [r"\end{longtable}", r"\endgroup"]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- figures

def fig_timeline(rows):
    years = sorted({r["year"] for r in rows if r["year"]})
    years = list(range(years[0], years[-1] + 1)) if years else []
    cols = level_cols(rows)
    per_year = Counter(r["year"] for r in rows if r["year"])
    ymax = max(per_year.values(), default=1)
    lines = [r"\begin{figure}[t]", r"\centering", r"\begin{tikzpicture}",
             r"\begin{axis}[rsi, ybar stacked, bar width=14pt, width=0.95\linewidth, height=5.2cm,",
             rf"  ymin=0, ymax={ymax + max(1, round(ymax * 0.12))}, enlarge x limits={0.5 if len(years) < 2 else 0.12},",
             rf"  xtick={{{','.join(map(str, years))}}}, xticklabel style={{/pgf/number format/1000 sep=}},",
             rf"  xlabel={{{TX['year']}}}, ylabel={{{TX['count']}}}, ymajorgrids, grid style={{black!10}},",
             r"  legend style={at={(0.02,0.98)}, anchor=north west}, legend columns=" + str(len(cols)) + ",",
             r"  area legend, axis x line*=bottom, axis y line*=left]"]
    for lv in cols:
        color = "rsiTBD" if lv == TBD else f"rsi{lv}"
        pts = " ".join(f"({y},{sum(1 for r in rows if r['year'] == y and r['level'] == lv)})" for y in years)
        lines.append(rf"\addplot[draw=none, fill={color}] coordinates {{{pts}}};")
        lines.append(rf"\addlegendentry{{{TX['tbd'] if lv == TBD else lv}}}")
    for y in years:                                   # year totals above the stacks
        lines.append(rf"\node[above, font=\footnotesize] at (axis cs:{y},{per_year.get(y, 0)}) "
                     rf"{{{per_year.get(y, 0)}}};")
    lines += [r"\end{axis}", r"\end{tikzpicture}", rf"\caption{{{TX['cap_timeline']}}}",
              r"\label{fig:rsi-timeline}", r"\end{figure}"]
    return "\n".join(lines) + "\n"


def fig_loop(rows):
    loops = LOOPS + ([TBD] if any(r["loop"] in ("", TBD) for r in rows) else [])
    colors = dict(zip(LOOPS, ["rsiLoopA", "rsiLoopB", "rsiLoopC"]), **{TBD: "rsiTBD"})
    doms = list(pl.DOMAINS)[::-1]                     # domain 0 on top
    xmax = max((sum(1 for r in rows if d in r["tag_list"]) for d in doms), default=1) or 1
    lines = [r"\begin{figure}[t]", r"\centering", r"\begin{tikzpicture}",
             r"\begin{axis}[rsi, xbar stacked, bar width=9pt, width=0.95\linewidth, height=4.8cm,",
             rf"  xmin=0, xmax={xmax}, ytick={{0,...,4}}, enlarge y limits=0.15,",
             "  yticklabels={" + ",".join("{" + TX["domains_short"][d] + "}" for d in doms) + "},",
             rf"  xlabel={{{TX['count']}}}, xmajorgrids, grid style={{black!10}}, y axis line style={{draw=none}},",
             r"  ytick style={draw=none}, axis x line*=bottom, area legend,",
             r"  legend style={at={(0.5,1.02)}, anchor=south}, legend columns=" + str(len(loops)) + "]"]
    for lp in loops:
        def n(d):
            return sum(1 for r in rows if d in r["tag_list"] and (r["loop"] or TBD) == lp)
        pts = " ".join(f"({n(d)},{i})" for i, d in enumerate(doms))
        lines.append(rf"\addplot[draw=none, fill={colors[lp]}] coordinates {{{pts}}};")
        lines.append(rf"\addlegendentry{{{TX['loop'][lp]}}}")
    lines += [r"\end{axis}", r"\end{tikzpicture}", rf"\caption{{{TX['cap_loop']}}}",
              r"\label{fig:rsi-loop}", r"\end{figure}"]
    return "\n".join(lines) + "\n"


def stats(rows):
    c = Counter(r["level"] for r in rows)
    lines = [rf"\newcommand{{\RSINumPapers}}{{{len(rows)}}}",
             rf"\newcommand{{\RSINumConfirmed}}{{{sum(r['status'] == pl.STATUS_CONFIRMED for r in rows)}}}",
             rf"\newcommand{{\RSINumFullText}}{{{sum(r['reading'] in pl.READ_IN_FULL for r in rows)}}}"]
    for lv, word in zip(LEVELS, ["Zero", "One", "Two", "Three", "Four"]):   # \RSINumRZero .. \RSINumRFour
        lines.append(rf"\newcommand{{\RSINumR{word}}}{{{c.get(lv, 0)}}}")
    names = "ABCDE"                                   # \RSINumDomainA .. E = domains 0..4
    for d, k in zip(pl.DOMAINS, names):
        lines.append(rf"\newcommand{{\RSINumDomain{k}}}{{{sum(d in r['tag_list'] for r in rows)}}}")
    years = [r["year"] for r in rows if r["year"]]
    lines.append(rf"\newcommand{{\RSIYearRange}}{{{min(years)}--{max(years)}}}" if years
                 else r"\newcommand{\RSIYearRange}{--}")
    return "\n".join(lines) + "\n"


